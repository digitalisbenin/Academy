            <h3 class="mb-4">Ce qui nous différencie : Notre pédagogie!</h3>
            <p>La <b>pédagogie mise en place par NigerAcademy donne une place prépondérante aux projets, en individuel, en binome, ou encore en mode studio sous forme de projet commun d’envergure</b>. Sur la base d'un plan de formation et d'un planning établis, les étudiants sont incités très tôt à apprendre dans le cadre de projets réels qui peuvent comporter des contraintes plus ou moins importantes permettant d'orienter le travail et les apprentissages. <b>L’apprentissage se fait ainsi sur le tas, en condition de travail, pour développer la capacité d’adaptation nécessaire aux métiers créatifs et technologiques</b>.</p>

            <p>Lorsque l’on veut apprendre à créer ou n’importe quel domaine créatif dans une école ou centre de formation au Niger ou à Niamey, voire à distance, de nombreuses questions peuvent se poser. <b>Les plus courantes tournent autour du prix ou du diplôme. Mais il ne faut pas oublier le contenu et les méthodes.<br>Si la question du prix est fondamentale</b> pour vous ou les familles, il faut cependant bien admettre qu’il y a un peu de tout : de 120.000 à plus de 1.500.000 Francs CFA l’année. Les écoles justifient leur prix différemment : matériel couteux, professeurs, cout de l’immobilier… Si tous ces éléments peuvent se comprendre, il reste à peser leur véritable intérêt dans la formation : <b>est-ce que le fait d’avoir un mur d’écran et des lumières colorées à l’entrée rend la formation meilleure pour autant?</b> Il appartient à chacun de mesurer l’effort financier qu’il veut réaliser et les arguments qui lui plaise.</p>
            
            <h3 class="mb-4">Apprendre en faisant</h3>
            <p>On pourrait faire la même objection sur les diplomes et certificats de formation, mais au final autant ce concentrer sur l’essentiel. <b>Et ce qui constitue l’essentiel d’une formation à NigerAcademy est lié à la pratique de l’enseignement</b>. En effet, les élèves ont accès à de nombreuses ressources sur internet, des millions de vidéos et de pages parfois pointues. <b>La plus-value qu’apportera un professeur sera d’accompagner l’étudiant à trouver ses repères et les bonnes informations par rapport à ses objectifs.</b> Car ce qui compte, ce n’est pas tant le projet de l’école que celui de l’étudiant.</p>

            <p>Dans ce cadre, NigerAcademy a décidé de travailler en mode projet/studio dans lesquels les étudiants apprennent quasi exclusivement par la pratique. Un <b>objectif d’apprentissage est donné sur une période</b> avec une production à réaliser et des contenus. Une démonstration initiale est souvent réalisée pour guider au lancement. Ensuite, l’apprenant avance en produisant avec le soutien pédagogique et technique de l’équipe. Si cette méthode change beaucoup des pratiques scolaires du collège et lycée, elle a l’<b>avantage d’être moins ennuyeuse, de placer l’étudiant dans une position active, et surtout le placer en situation professionnelle dans laquelle il devra remplir des objectifs et trouver les moyens de les remplir, dans un temps donné, avec l’aide d’accompagnant qui sont là pour le guider</b>. Cette méthode dissocie beaucoup moins les contenus et chaque projet aborde nécessairement plusieurs aspects ce qui permet de donner un sens à l’avancée.</p>

            <p>Dans le contexte de tous les métiers de la création et du développement, cette pratique nous semble essentielle. Enfin, cette méthode place très tôt les étudiants en situation professionnelles : <b>réaliser des objectifs, respecter un délai de production, se répartir des tâches, penser au résultat avant de penser à soi…</b></p>
            
            <h3 class="mb-4">Organisation pédagogique</h3>
            <p>Des objectifs sont donnés sur une période : <b>objectif principal et des objectifs secondaires</b>. La période peut aller de 1 à 5 semaines. A la fin de chaque période, on a une production livrée.<br>
            La période peut éventuellement être découpée en plusieurs "morceaux" pour focaliser spécifiquement sur certains aspects.</p>

            <p>Dans <b>le cadre des formations à distance, la même organisation est préservée</b>. Les périodes durent jusqu’au vendredi pour permettre les adaptations de planning personnelles et elles sont d’une durée volontairement plus courte pour assurer un suivi plus régulier et préserver l’engagement personnel.</p>
            
            <h3 class="mb-4">Encadrement pédagogique</h3>
            <p><b>NigerAcademy met un point d’honneur à accompagner au mieux les apprenants</b>. Dans les cours de programmation, du marketing et tous les autres cours, le taux d’encadrement est d’au maximum 1 professeur ou tuteur pour 8 à 10 élèves. Dans certains cours, il est de 5 pas plus. Pour les élèves en grande difficulté sur certains sujets, il peut nous arriver exceptionnellement de déployer un tuteur pour un accompagnement personnalisé de plusieurs jours.</p>

            <p>Nous estimons que ces conditions sont nécessaires pour :</p>
            <ul class="list-styled">
              <li>individualiser au maximum l’aide que nous apportons</li>
              <li>ne pas laisser un apprenant trop longtemps dans l’attente d’un soutien</li>
              <li>prendre le temps de comprendre le projet dans lequel on travaille, et aider l’apprenant à trouver par lui-même à comprendre ses erreurs en le guidant peu à peu.</li>
            </ul>
            Dans nos formations, tout est mis en place pour favoriser la progression de tous.
