document.getElementById('inputCursus').addEventListener('change', function() {
    var filiereSelect = document.getElementById('inputFiliere');
    filiereSelect.innerHTML = '<option selected>Veuillez sélectionner</option>'; // Réinitialiser les options

    var selectedOptions = this.selectedOptions[0];
    var filieres = JSON.parse(selectedOptions.getAttribute('data-filiere')); // Récupérer les filières

    if (filieres.length) {
        filieres.forEach(function(filiere) {
            var option = document.createElement('option');
            option.value = filiere.id;
            option.textContent = filiere.name; // Remplacez par le champ correct pour le nom
            filiereSelect.appendChild(option);
        });
    }
});

