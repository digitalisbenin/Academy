        <h2>Les formations à choisir en fonction de votre spécialité au Bac</h2>
         <p>La formation postbac : un choix déterminant :<br>
          Vous venez de décrocher votre bac? Félicitations, vous êtes à présent sur le point de prendre la décision la plus importante de votre parcours d’étudiant : <b>choisir votre formation universitaire</b>. Plusieurs options vont se présenter à vous, selon votre spécialité. Et nous vous rappellerons que <b>le critère premier est de choisir une formation qui vous plait, qui convient à vos aspirations et qui soit en phase avec votre bac.<br> Nous allons donc vous parler des formations possibles après les 3 principales spécialités au bac : scientifique, économique et littéraire.</p>

          <h4>Bac Scientifique : quelles formations</h4>
          <p>Si vous êtes détenteur d’un bac spécialité scientifique ou littéraire, plusieurs choix de formations se présentent à vous, selon vos aspirations. Il y a les grandes écoles de commerce pour suivre un parcours en management et gestion. Ensuite, les facultés et leurs spécialités scientifique : mathématiques, chimie, physique, biologie, génie civile, etc. Mais également la faculté de médecine générale, dentaire ou de pharmacie. Il existe aussi les FST : Facultés de Sciences et Techniques ainsi que les Instituts Agronomiques et Vétérinaires. Une autre option intéressante est la formation d’ingénieurs, au sein des différentes écoles d’ingénieurs. Finalement, vous pouvez aussi opter pour des études d’architecture.</p>
         
          <h4>Bac Économie : quels choix</h4>
          <p>Après votre spécialité au bac, vous êtes déjà familiers avec la gestion et l’économie, mais vous devez choisir les formations qui vont dans le même sens. Comme formations à choisir, tout d’abord, les grandes écoles et instituts de commerce. Mais aussi les différents instituts de management et de commerce. Vous pouvez aussi choisir les facultés des sciences juridiques, économiques et sociales. Vous pouvez également opter pour des études en arts dramatiques ou en journalisme et communication.</p>

          <h4>Bac Littéraire : quelles voies</h4>
          <p>À l’issue d’un bac spécialité littéraire, vous avez également bon nombre de formations qui compléteront vos acquis du lycée et seront une voix logique à envisager.
          Premièrement, les facultés des lettres et sciences humaines, ou des sciences juridiques, économiques et sociales, mais aussi des Sciences de l’éducation. Vous avez également accès aux instituts de tourisme, de technologie appliquée, de journalisme et de communication. Ensuite, une autre voie à considérer est les Facultés des Sciences de l’éducation, etc. Dans le cas où vous souhaitez poursuivre des études en art, il existe aussi L’École des Beaux-Arts.</p>

          <h4>Vous hésitez encore dans votre choix?</h4>
          <p>Si vous venez de décrocher votre bac et semblez ne pas avoir une idée claire sur votre avenir, vous avez des questions sur votre orientation ou souhaitez intégrer une ecole ou centre de formation de courte durée? Contactez-nous dès maintenant pour découvrir notre programme.</p>
